package D1_Intro;

// Main Concept
// source code (.java) -> Compiler (JDK) -> Byte code (.class). This is called Compiler stage.
// Byte code converts (by JVM) into native code (which machine can understand). This process called Execution.

public class FirstClass {
    static void main(String[] args) {
        System.out.println("Hello World");
    }
}

//Functions
//A function is a block of code which takes some input, performs some operations and returns some output.
//The functions stored inside classes are called methods.
//The function we have used is called main.

//Class
//A class is a group of objects which have common properties.
//A class can have some properties and functions (called methods).
//The class we have used is FirstClass.
